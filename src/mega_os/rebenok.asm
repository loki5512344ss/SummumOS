; ребёнок вылез из файла и требует кашу. кашу выдают через INT 2.
; собран под 0x4000, поэтому все прыжки абсолютные, как у взрослых.
rebenok:
ldi r0, 1
ldi r1, rebenok_text
ldi r2, 6
int 2
; --- изоляция памяти: в своей квартире пишем чужой байт ---
ldi r0, 0xaa
ldi r1, 0xa000
stb [r1], r0
; --- ждём общий флаг 0x8204: родитель умрёт, когда ВСЕ дети засели. Пока
; флага нет -- крутимся, обе котлеты обязаны быть живы одновременно. ---
rebenok_zhdet_flag:
ldi r0, 0x8204
ld r1, [r0]
jz r1, rebenok_zhdet_flag
ldi r0, 4
ldi r1, 0
int 2
jmp rebenok
rebenok_text:
.str "child\n"
