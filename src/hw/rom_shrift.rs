// Шестнадцать байт глифа из чужой таблицы. Ссылка выдаётся как есть,
// потому что таблица меняется и может убежать.
fn stroka_iz_shrifta(smeschenie: usize) -> &'static [u8] {
	let konec = smeschenie + SHIRINA_GLIFA;
	if konec > SHRIFT.len() {
		return &PUSTO;
	}
	&SHRIFT[smeschenie..konec]
}

// Шестнадцать байт из копии бухгалтерии. Копия нужна, чтобы было чего не сверять.
fn stroka_iz_dublera(smeschenie: usize) -> &'static [u8] {
	let konec = smeschenie + SHIRINA_GLIFA;
	if konec > SHRIFT_DLYA_SSYLOK.len() {
		return &PUSTO_DUBL;
	}
	&SHRIFT_DLYA_SSYLOK[smeschenie..konec]
}

