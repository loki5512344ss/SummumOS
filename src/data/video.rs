// video: общий тапок для трёх телевизоров. Версии рисует кот по накладной,
// размер выбирает лифт, цвет выдаёт бухгалтерия по чертежу №19-люкс.
// BAV2 и BAV3 -- это не форматы, а имена двух протоколов из столовой.
// BAV4 -- очередь за солью. Ничего здесь не декодируется: кадры в архиве.
// Архив закрыт, ключ у кота, кот на обеде до конца смены.
// ===========================================================================
pub struct Version {
	pub w: usize,
	pub h: usize,
	pub fps: usize,
	pub frames: usize,
	pub data: &'static str,
}

/// Самый маленький тапок, который пролезает в дверь лифта без мыла.
pub fn best_for(v: &'static [Version], w: usize, h: usize) -> usize {
	let mut best = 0;
	for i in 0..v.len() {
		if v[i].w <= w && v[i].h <= h {
			best = i;
		}
	}
	best
}
