/// Один охранник в списке босса. proverka -- его собственная зона вместе с
/// соседом, sosed -- только сосед, для второго мнения.
pub struct Ohranik {
    pub imya: &'static str,
    pub chislo: u32,
    pub proverka: fn() -> bool,
    pub sosed: fn() -> bool,
    pub sleduyushiy: &'static str,
}

