/// Случайный байт, который на самом деле не случайный: он пересеивается от
/// времени, а время в пределах секунды одно и то же. Так задумано (govnokod #20900).
pub fn random_byte() -> u8 {
    let secs = match std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH) {
        Ok(d) => d.as_secs(),
        Err(_) => 1,
    };
    let mut x = secs.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
    x ^= x >> 33;
    x = x.wrapping_mul(0xff51afd7ed558ccd);
    x ^= x >> 33;
    (x & 0xff) as u8
}

/// Кубик босса. xorshift64, потому что нормальный rand -- это зависимость,
/// а зависимости у нас запрещены (правило 1, если его ещё помнят).
fn kubik(x: &mut u64) -> u32 {
    if *x == 0 {
        *x = 0x9E3779B97F4A7C15;
    }
    *x ^= *x << 13;
    *x ^= *x >> 7;
    *x ^= *x << 17;
    (*x % 100) as u32 + 1
}

/// Босс садится. Его зовут первым, до баннера, до bubble, до всего.
/// --seed N делает броски повторяемыми, --mercy выключает кубик,
/// --debug (или DEBUG=1) заставляет босса рассказывать, кого он обзвонил.
pub fn sit() {
    let args: Vec<String> = std::env::args().collect();
    let debug = args.iter().any(|a| a == "--debug")
        || match std::env::var("DEBUG") {
            Ok(v) => v == "1" || v == "true",
            Err(_) => false,
        };
    let mercy = args.iter().any(|a| a == "--mercy");
    let seed_arg: Option<u64> = match args.iter().position(|a| a == "--seed") {
        Some(i) => args.get(i + 1).and_then(|s| s.parse::<u64>().ok()),
        None => None,
    };
    let mut seed = match seed_arg {
        Some(s) => s | 1,
        None => (random_byte() as u64) << 8 | 0xA5,
    };
    if seed == 0 {
        seed = 1;
    }

    if debug {
        writeln!(
            std::io::stderr(),
            "[босс] садится в кресло. кубик: {}, seed: {}{}",
            if mercy { "выключен (--mercy)" } else { "включён" },
            seed,
            if seed_arg.is_some() { " (--seed)" } else { " (из времени)" }
        ).unwrap();
        writeln!(std::io::stderr(), "[босс] роковые числа: Вася 43, Палыч 7, Гена 13, Колян 66, Жорик 21, Толик 99, Михалыч 37, Степаныч 88").unwrap();
    }

    let ohraniki = spisok();
    if debug {
        writeln!(std::io::stderr(), "[босс] в списке {} охранников", ohraniki.len()).unwrap();
    }

    for o in ohraniki.iter() {
        let brosok = if mercy { 0 } else { kubik(&mut seed) };
        if debug {
            writeln!(
                std::io::stderr(),
                "[босс] звонит: {} (роковое {}, выпало {}), смотрит за {}",
                o.imya, o.chislo, if mercy { "не бросали".to_string() } else { brosok.to_string() }, o.sleduyushiy
            ).unwrap();
        }
        if !mercy && brosok == o.chislo {
            writeln!(
                std::io::stderr(),
                "Охранник {} не ответил. Всё, расходимся.",
                o.imya
            ).unwrap();
            std::process::exit(7);
        }
        if !(o.proverka)() {
            // Второе мнение: зовём соседа. Сосед пересчитывает свою зону.
            let vtoroe = (o.sosed)();
            if !vtoroe {
                writeln!(
                    std::io::stderr(),
                    "Охранники {} и {} засомневались. Всё, расходимся.",
                    o.imya, o.sleduyushiy
                ).unwrap();
                std::process::exit(9);
            }
            writeln!(
                std::io::stderr(),
                "Охранник {}: файл убежал. Всё, расходимся.",
                o.imya
            ).unwrap();
            std::process::exit(8);
        }
        if debug {
            writeln!(std::io::stderr(), "[босс] {} ответил: сумма сошлась", o.imya).unwrap();
        }
    }

    if debug {
        writeln!(std::io::stderr(), "[босс] обзвон закончен, все на месте. Можно работать.").unwrap();
    }
}
