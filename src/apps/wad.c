/* WAD-ЧИТАТЕЛЬ v0.1. Настоящий парсер WAD, который работает на процессоре из
   NAND, а не на ноутбуке. Диск здесь -- это три байта адреса (0xFF30, 0xFF31,
   0xFF32) и один байт данных (0xFF33). Байт данных сам прибавляет единицу к
   адресу, поэтому читать надо подряд, как книгу, только задом наперёд и в
   темноте.

   Файл в память НЕ грузим: у машины 64 КБ, у WAD больше. Мы ползём по диску
   и тащим с собой только три байта адреса и дурные намерения.

   Что умеем: найти E1M1, выдрать THINGS, LINEDEFS и VERTEXES и нарисовать
   карту сверху. Что не умеем: BSP, стены, высоту, секторы, двери, монстров,
   звук, играть. То есть это не Doom, а его вид сверху, который устал.

   Компилятор C у нас свой и маленький: структур, перечислений, дробей,
   переключателей и typedef тут нет. Указатели есть, но мы делаем вид, что
   они не кусаются. */

/* Адрес диска живёт в трёх байтах, потому что 16 бит на 24 бита не делятся.
   c0 -- младший, c1 -- средний, c2 -- старший. Старший байт адреса WAD мы
   всё равно не читаем: файлы больше 16 МБ эта машина не переживёт. */
int c0; int c1; int c2;

/* Имя блока из каталога. Восемь байт, без нуля на конце, как в настоящем WAD.
   Девятый байт не поместился, поэтому имена длиннее восьми мы не узнаём. */
char nm[8];

/* Где в каталоге лежит E1M1. Минус один -- не нашли, и тогда вся затея --
   просто чтение диска ради чтения диска. */
int e1i;

/* Адреса трёх нужных блоков. Каждый -- три байта, как положено.
   Размеры -- в байтах, но только младшие 16 бит: E1M1 в них влезает, а
   карта размером с Луну -- нет. */
int t0; int t1; int t2; int tsz; int has_t;
int l0; int l1; int l2; int lsz; int has_l;
int v0; int v1; int v2; int vsz; int has_v;

/* Сколько записей нашли. Считаем делением размера блока, а не пересчётом
   руками: руки у нас тоже 16-битные. */
int nt; int nl; int nv;

/* Границы карты. Нужны, чтобы впихнуть весь E1M1 в 64 на 24 клетки.
   Настоящий Doom рисует в 320 на 200 и не жалуется, но у него есть память. */
int minx; int maxx; int miny; int maxy;
int stepx; int stepy;

/* Сюда временно складывается вершина, которую только что прочитали с диска.
   Массив вершин не держим: 64 КБ -- это не склад, а почтовый ящик. */
int gvx; int gvy;

/* Видеопамять. 64 на 24 байта, адрес 0xF000. Буквы, не пиксели.
   0xFF20 -- это 3872 байта дальше, там живёт кнопка "показать кадр". */
char *vram;

/* Ставим головку диска на адрес из трёх байт. Порядок важен: младший,
   средний, старший. Если перепутать, диск начнёт читать чужое. */
void sk(int a0, int a1, int a2) {
    char *p;
    p = (char *)0xFF30;
    *p = a0;
    p = p + 1;
    *p = a1;
    p = p + 1;
    *p = a2;
    c0 = a0; c1 = a1; c2 = a2;
}

/* Читаем один байт и сами двигаем адрес. Железо двигает его тоже, но мы
   не доверяем железу: оно двигает молча. */
int rb() {
    char *p; int v;
    p = (char *)0xFF33;
    v = *p;
    c0 = c0 + 1;
    if (c0 >= 256) {
        c0 = 0;
        c1 = c1 + 1;
        if (c1 >= 256) { c1 = 0; c2 = c2 + 1; }
    }
    return v;
}

/* Ставим головку на base + off, где off не больше 65535. Три байта складываем
   по частям, потому что 24-битных чисел у компилятора нет. */
void sk_off(int a0, int a1, int a2, int off) {
    int lo; int mid;
    lo = off & 255;
    a0 = a0 + lo;
    if (a0 >= 256) { a0 = a0 - 256; a1 = a1 + 1; }
    mid = (off >> 8) & 255;
    a1 = a1 + mid;
    if (a1 >= 256) { a1 = a1 - 256; a2 = a2 + 1; }
    sk(a0, a1, a2);
}

/* Два байта, младший вперёд. Так написано в спецификации, а спецификацию
   писали люди, у которых не было NAND. */
int rd_u16() {
    int lo; int hi;
    lo = rb();
    hi = rb();
    return lo + hi * 256;
}

/* Два байта со знаком. Если старший байт укусил, приклеиваем 0xFF00:
   16-битное слово само решит, что оно отрицательное. Пусть решает. */
int rd_i16() {
    int v; int hi;
    v = rb();
    hi = rb();
    v = v + hi * 256;
    if (hi >= 128) v = v | 65280;
    return v;
}

/* Пропустить n байт. Полезно, когда запись длиннее, чем нам интересно.
   Диск всё равно их прочитает, но мы сделаем вид, что не видели. */
void skip(int n) {
    int i;
    i = 0;
    while (i < n) { rb(); i++; }
}

/* Проверка сигнатуры. IWAD и PWAD -- это одно и то же, только один гордый. */
int is_wad() {
    int a; int b; int c; int d;
    a = rb(); b = rb(); c = rb(); d = rb();
    if (a == 'I' && b == 'W' && c == 'A' && d == 'D') return 1;
    if (a == 'P' && b == 'W' && c == 'A' && d == 'D') return 1;
    return 0;
}

/* Сравниваем имя блока с константой. В nm нет нуля на конце, поэтому после
   совпадения букв ещё проверяем, что имя кончилось, а не продолжается. */
int nm_is(char *s) {
    int i;
    i = 0;
    while (s[i] && i < 8) {
        if (nm[i] != s[i]) return 0;
        i++;
    }
    /* Имя ровно из восьми букв не имеет нуля на конце: все восемь байт
       заняты делом. Дальше читать nm нельзя, там уже чужие глобалы. */
    if (i >= 8) return 1;
    return nm[i] == 0;
}

/* Идём по каталогу и ищем E1M1, а после него -- три блока карты.
   Для настоящего IWAD они всегда идут сразу после метки E1M1, потому что
   так решили в 1993 году и с тех пор не пересматривали.

   Запись каталога -- 16 байт: адрес 4, размер 4, имя 8. В задании написали
   "12", но 4 плюс 4 плюс 8 всё равно 16, а спорить с арифметикой и Doom
   одновременно -- это уже две драки. */
void scan_dir(int cnt) {
    int i; int k; int a0; int a1; int a2; int s0; int s1;
    e1i = 0 - 1;
    has_t = 0; has_l = 0; has_v = 0;
    i = 0;
    while (i < cnt) {
        a0 = rb(); a1 = rb(); a2 = rb(); rb();
        s0 = rb(); s1 = rb(); rb(); rb();
        for (k = 0; k < 8; k++) nm[k] = rb();
        if (nm[0] == 'E' && nm_is("E1M1")) {
            e1i = i;
        } else if (e1i >= 0) {
            /* Блоки до E1M1 нас не волнуют: это чужие карты и палитры. */
            if (nm[0] == 'T' && nm_is("THINGS") && !has_t) {
                t0 = a0; t1 = a1; t2 = a2;
                tsz = s0 + s1 * 256; has_t = 1;
            }
            if (nm[0] == 'L' && nm_is("LINEDEFS") && !has_l) {
                l0 = a0; l1 = a1; l2 = a2;
                lsz = s0 + s1 * 256; has_l = 1;
            }
            if (nm[0] == 'V' && nm_is("VERTEXES") && !has_v) {
                v0 = a0; v1 = a1; v2 = a2;
                vsz = s0 + s1 * 256; has_v = 1;
            }
        }
        i++;
    }
}

/* Расширяем границы карты одной точкой. */
void touch(int x, int y) {
    if (x < minx) minx = x;
    if (x > maxx) maxx = x;
    if (y < miny) miny = y;
    if (y > maxy) maxy = y;
}

/* Первый проход: узнаём, где у карты край. Вершины не запоминаем, потому что
   запоминать негде. Второй раз мы их прочитаем, когда будем рисовать. */
void bounds() {
    int i; int x; int y;
    minx = 32000; maxx = 0 - 32000;
    miny = 32000; maxy = 0 - 32000;
    if (nv > 0) {
        sk(v0, v1, v2);
        i = 0;
        while (i < nv) {
            x = rd_i16();
            y = rd_i16();
            touch(x, y);
            i++;
        }
    }
    if (nt > 0) {
        sk(t0, t1, t2);
        i = 0;
        while (i < nt) {
            x = rd_i16();
            y = rd_i16();
            skip(6);
            touch(x, y);
            i++;
        }
    }
}

/* Подбираем шаг деления. Умножать координату на 63 нельзя: 16-битное
   произведение лопнет. Поэтому делим на заранее подобранный шаг. */
void scale() {
    int sx; int sy;
    sx = maxx - minx;
    sy = maxy - miny;
    if (sx <= 0) sx = 1;
    if (sy <= 0) sy = 1;
    stepx = sx / 63;
    stepy = sy / 23;
    if (stepx < 1) stepx = 1;
    if (stepy < 1) stepy = 1;
}

/* Координата карты в колонку экрана. Разность неотрицательная, поэтому
   деление не спорит со знаком. */
int sx_of(int x) {
    int s;
    s = (x - minx) / stepx;
    if (s < 0) s = 0;
    if (s > 63) s = 63;
    return s;
}

/* То же, но в строку. Строк меньше, поэтому шаг другой. */
int sy_of(int y) {
    int s;
    s = (y - miny) / stepy;
    if (s < 0) s = 0;
    if (s > 23) s = 23;
    return s;
}

/* Одна буква в кадр. За границей экрана буква уходит в отпуск. */
void plot(int x, int y, int ch) {
    if (x < 0 || x > 63 || y < 0 || y > 23) return;
    vram[y * 64 + x] = ch;
}

/* Линия Брезенхэма. Настоящий Doom рисует стены в 3D, а мы рисуем их
   карандашом на клетчатом листке. */
void bline(int x0, int y0, int x1, int y1) {
    int dx; int dy; int sx; int sy; int err; int e2;
    dx = x1 - x0; if (dx < 0) dx = 0 - dx;
    dy = y1 - y0; if (dy < 0) dy = 0 - dy;
    sx = 1; if (x0 > x1) sx = 0 - 1;
    sy = 1; if (y0 > y1) sy = 0 - 1;
    err = dx - dy;
    while (1) {
        plot(x0, y0, '#');
        if (x0 == x1 && y0 == y1) return;
        e2 = err * 2;
        if (e2 > (0 - dy)) { err = err - dy; x0 = x0 + sx; }
        if (e2 < dx) { err = err + dx; y0 = y0 + sy; }
    }
}

/* Читаем вершину по номеру. Именно тут мы прыгаем по диску туда-сюда,
   потому что LINEDEFS хранят номера, а не координаты. */
void getv(int idx) {
    sk_off(v0, v1, v2, idx * 4);
    gvx = rd_i16();
    gvy = rd_i16();
}

/* Рисуем все линии. По каждой записи читаем два номера вершин, потом бежим
   за самими вершинами. Массив линий не держим: память не резиновая. */
void draw_lines() {
    int i; int a; int b; int x0; int y0; int x1; int y1;
    i = 0;
    while (i < nl) {
        sk_off(l0, l1, l2, i * 14);
        a = rd_u16();
        b = rd_u16();
        getv(a);
        x0 = gvx; y0 = gvy;
        getv(b);
        x1 = gvx; y1 = gvy;
        bline(sx_of(x0), sy_of(y0), sx_of(x1), sy_of(y1));
        i++;
    }
}

/* Игрок, монстры, бочки и выход -- всё это THINGS. Нам нужны только первые
   четыре байта, остальные шесть -- это угол, тип и флаги, то есть слухи. */
void draw_things() {
    int i; int x; int y;
    sk(t0, t1, t2);
    i = 0;
    while (i < nt) {
        x = rd_i16();
        y = rd_i16();
        skip(6);
        plot(sx_of(x), sy_of(y), '+');
        i++;
    }
}

/* Заливаем кадр пробелами. Пробел -- это фон, пустота и вообще всё сразу. */
void clear_frame() {
    int i;
    i = 0;
    while (i < 1536) { vram[i] = ' '; i++; }
}

int main() {
    int cnt; int b0; int d0; int d1; int d2;
    vram = (char *)0xF000;

    /* Заголовок: сигнатура, число блоков, адрес каталога. */
    sk(0, 0, 0);
    if (!is_wad()) {
        print("wad: это не WAD\n");
        return 1;
    }
    b0 = rb();
    cnt = b0 + rb() * 256;
    rb(); rb();
    d0 = rb(); d1 = rb(); d2 = rb(); rb();

    /* Каталог лежит в конце файла. Идём туда и читаем всё подряд.
       Сначала как настоящий Doom (16 байт), потом как велело задание (12). */
    sk(d0, d1, d2);
    scan_dir(cnt);
    if (e1i < 0) {
        print("wad: E1M1 не нашлась, и это не наша вина\n");
        return 1;
    }
    if (!has_t || !has_l || !has_v) {
        print("wad: у E1M1 отвалились блоки\n");
        return 1;
    }

    nt = tsz / 10;
    nl = lsz / 14;
    nv = vsz / 4;

    clear_frame();
    bounds();
    scale();
    draw_lines();
    draw_things();

    /* 3872 -- это 0xFF20 минус 0xF000. Видеокарта смотрит именно сюда. */
    vram[3872] = 1;

    /* Отчёт. Числа настоящие, гордость тоже. */
    print("wad: things=");
    print_num(nt);
    print(" lines=");
    print_num(nl);
    print(" verts=");
    print_num(nv);
    putnl();
    return 0;
}
