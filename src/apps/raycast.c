/* РЕЙКАСТЕР v1.0. Настоящий Doom, только без дверей, монстров, оружия,
   звука, текстур и цвета. Зато 64 луча -- ровно столько, сколько влезло
   в 16 бит, если считать на пальцах одной ноги.

   Мир -- карта 16 на 16 клеток. Решётка -- стена, точка -- пол.
   Игрок -- две координаты в формате 8.8: целая часть это клетка, дробная
   это как далеко он ушёл за хлебом. Угол -- число от 0 до 15, потому что
   синус на этой машине считают только избранные, а мы считаем таблицей.

   Луч идёт шагами по половине клетки и спрашивает карту: "ты стена?".
   Если стена -- рисуем символ. Чем дальше, тем символ печальнее.
   Потолок обозначен волной, пол -- подчёркиванием, а стены -- символами
   от @ до пробела. Всё это лежит в видеопамяти 0xF000, по одному байту
   на клетку. Кадр показывается записью единицы в 0xFF20: видеокарта
   смотрит на неё и делает вид, что ей интересно.

   Компилятор C у нас свой, поэтому здесь нет структур, переключателей,
   дробей, typedef и указателей на функции. Указатели на массивы есть,
   но мы их не трогаем: они кусаются. */

/* Карта. Одна длинная строка, потому что массив с инициализатором
   компилятор съедает только по одной константе, а строчки клеить
   в глобальной области он не умеет. 16 раз по 16 -- это 256 байт,
   столько же, сколько клеток на экране. Совпадение, конечно. */
char *map = "#################..............##..#.....#.....##..#.....#.....##..#..###......##..............##....######....##..............##......#.......##......#.......##......#.......##..............##...##....###..##..............##..............#################";

/* Палитра стен: близко -- страшно, далеко -- пусто. Ровно 10 символов,
   потому что больше в голове не помещается. */
char *pal = "#@%*+=-:. ";

/* Куда смотрит игрок. Векторы в 8.8, то есть 256 -- это единица.
   Таблицу заполняем руками: 16 направлений, шаг 22.5 градуса.
   Настоящий Doom считает их сам, но он и не работает на NAND. */
int dirx[16];
int diry[16];
int plx[16];
int ply[16];

/* Где стоит игрок и куда повёрнут. Угол -- индекс в таблице, а не градусы:
   градусы тут никто не проверял. */
int px;
int py;
int ang;

/* Сюда складываются шаги лучей текущего кадра. Массив глобальный, чтобы не
   тратить стек: стек у нас тоже из NAND и тоже устаёт. Внутри не направление,
   а уже готовый шаг за один тик -- так дешевле, чем умножать на каждом шагу. */
int rayx[64];
int rayy[64];

/* Умножаем и делим на 256 руками, потому что отрицательные числа наш
   процессор делит как хочет, а точнее -- как беззнаковые. Сначала
   отрываем знаки, потом приклеиваем обратно. */
int smul(int a, int b) {
    int s; int r;
    s = 1;
    if (a < 0) { a = 0 - a; s = 0 - 1; }
    if (b < 0) { b = 0 - b; s = 0 - s; }
    r = (a * b) / 256;
    if (s < 0) r = 0 - r;
    return r;
}

/* Делим на два со знаком. Умножать тут нечего: половина -- это сдвиг,
   а знак приклеиваем обратно, чтобы процессор не думал, что мы шутим. */
int half(int v) {
    if (v < 0) return 0 - ((0 - v) >> 1);
    return v >> 1;
}

/* Свободна ли клетка. За границей карты всегда стена, там живут баги.
   Делим на 256 сдвигом: число уже проверено на неотрицательность, а
   отрицательное деление наш процессор всё равно понимает по-своему. */
int free_at(int x, int y) {
    int cx; int cy;
    if (x < 0 || y < 0) return 0;
    if (x >= 4096 || y >= 4096) return 0;
    cx = x >> 8;
    cy = y >> 8;
    if (map[(cy * 16) + cx] == '#') return 0;
    return 1;
}

/* Заполняем таблицу направлений. Восемь штук считаем, остальные восемь
   получаются отрицанием: математика у нас экономная. */
void init_dirs() {
    int i;
    dirx[0] = 256; diry[0] = 0;
    dirx[1] = 237; diry[1] = 98;
    dirx[2] = 181; diry[2] = 181;
    dirx[3] = 98; diry[3] = 237;
    dirx[4] = 0; diry[4] = 256;
    dirx[5] = 0 - 98; diry[5] = 237;
    dirx[6] = 0 - 181; diry[6] = 181;
    dirx[7] = 0 - 237; diry[7] = 98;
    for (i = 0; i < 8; i++) {
        dirx[8 + i] = 0 - dirx[i];
        diry[8 + i] = 0 - diry[i];
    }
    /* Плоскость камеры -- это направление, повёрнутое на 90 градусов
       и умноженное на 0.66. 169 -- это 0.66 в 8.8, если верить калькулятору. */
    for (i = 0; i < 16; i++) {
        plx[i] = 0 - smul(diry[i], 169);
        ply[i] = smul(dirx[i], 169);
    }
}

/* Луч идёт вперёд шагами по половине клетки и считает, сколько их влезло
   до стены. Больше 20 шагов не делаем: дальше уже не стена, а философия.
   Шаг лежит в rayx/rayy, поэтому тут только сложение: делить на каждом
   шагу -- это для тех, у кого есть сопроцессор. Клетку и дробную часть
   тащим отдельно, чтобы не сдвигать координату на каждом шагу. */
int march(int i) {
    int cx; int cy; int xf; int yf; int n;
    cx = px >> 8;
    cy = py >> 8;
    xf = px & 255;
    yf = py & 255;
    n = 0;
    while (n < 20) {
        xf = xf + rayx[i];
        yf = yf + rayy[i];
        n++;
        if (xf < 0) { xf = xf + 256; cx = cx - 1; }
        else if (xf >= 256) { xf = xf - 256; cx = cx + 1; }
        if (yf < 0) { yf = yf + 256; cy = cy - 1; }
        else if (yf >= 256) { yf = yf - 256; cy = cy + 1; }
        if (cx < 0 || cy < 0) return n;
        if (cx >= 16 || cy >= 16) return n;
        if (map[(cy * 16) + cx] == '#') return n;
    }
    return 20;
}

/* Рисуем один кадр. 64 колонки, 24 строки, ни одного пикселя. */
void render_frame() {
    int col; int row; int cam; int far; int top; int bot; int ch; int w; int dx; int dy;
    char *vram;
    char *p;
    vram = (char *)0xF000;
    /* Сначала все 64 луча: игрок смотрит прямо, а по краям кадра косит.
       Сразу считаем шаг на один тик, чтобы луч не умножал на бегу. */
    for (col = 0; col < 64; col++) {
        cam = (col - 32) * 8;
        dx = dirx[ang] + smul(plx[ang], cam);
        dy = diry[ang] + smul(ply[ang], cam);
        rayx[col] = half(dx);
        rayy[col] = half(dy);
    }
    /* Теперь каждый луч красит свою колонку. Стена тем выше, чем ближе:
       далёкая стена -- это две строчки и надежда. */
    for (col = 0; col < 64; col++) {
        w = march(col);
        far = w >> 1;
        if (far > 9) far = 9;
        top = 2 + far;
        bot = 21 - far;
        p = vram + col;
        for (row = 0; row < 24; row++) {
            if (row < top) ch = '~';
            else if (row > bot) ch = '_';
            else ch = pal[far];
            *p = ch;
            p = p + 64;
        }
    }
    /* 3872 -- это 0xFF20 минус 0xF000. Видеокарта ждёт именно там. */
    vram[3872] = 1;
}

int main() {
    int f; int nx; int ny;
    init_dirs();
    px = 640;      /* 2.5 клетки по горизонтали */
    py = 1408;     /* а это 5.5 клетки вниз: оттуда хоть что-то видно */
    ang = 0;
    f = 0;
    while (f < 8) {
        /* Поворачиваемся и едем вперёд. Если впереди стена -- стоим и
           делаем вид, что так и задумано. */
        ang = (ang + 1) & 15;
        nx = px + smul(dirx[ang], 64);
        ny = py + smul(diry[ang], 64);
        if (free_at(nx, ny)) {
            px = nx;
            py = ny;
        }
        render_frame();
        f++;
    }
    print("raycast 64x24 8 frames\n");
    return 0;
}
